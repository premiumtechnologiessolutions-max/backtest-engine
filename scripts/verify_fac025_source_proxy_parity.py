"""Independent FAC025 source BID-proxy vs canonical run/run_fast parity gate.

No quote upload, no broker-fill authentication, no OOS certification.
This checks frozen *selected* shared-capacity trades and every observed M1
close-equity mark, rather than adding 72 standalone P/L streams.
"""
from __future__ import annotations

import argparse
from hashlib import sha256
import json
from pathlib import Path
import zipfile

import numpy as np
import pandas as pd

from norisk_quant.execution import run
from norisk_quant.fast_engine import run_fast
from norisk_quant.model import Settings, Signal
from scripts import research_fac025_source_one_slot as source

STRATEGY = "FAC025_SOURCE_SELECTED_ONE_SLOT_PARITY"


def _source_equity_marks(rows: list[dict], trades: list[dict]) -> np.ndarray:
    """Rebuild source BID close-equity independently from the trade ledger."""
    close = np.fromiter((r["c"] for r in rows), dtype=np.float64, count=len(rows))
    marks = np.empty(len(rows), dtype=np.float64)
    realized = 0.0
    cursor = 0
    for trade in trades:
        entry, exit_ = trade["entry_idx"], trade["exit_idx"]
        if not cursor <= entry <= exit_ < len(rows):
            raise AssertionError("Invalid source one-slot chronology")
        marks[cursor:entry] = realized
        marks[entry:exit_] = (
            realized + trade["side"] * (close[entry:exit_] - trade["entry_price"]) - source.FEE
        )
        realized += trade["net"]
        cursor = exit_
    marks[cursor:] = realized
    return marks


def verify_rows(rows: list[dict], candidates: list[dict] | None = None) -> dict:
    """Fail on any trade/fee/month/M1 equity discrepancy; emit aggregate only.

    Optional candidates are exclusively for synthetic regression fixtures.
    In the private-source path, candidates are regenerated by the frozen
    causal source signal builder and all 72 IDs share one position.
    """
    source.validate_source(rows)
    if candidates is None:
        candidates, _ = source.generate_candidates(rows)
    trades, skipped = source.replay(candidates, rows, source.frozen_specs())
    expected = source.score(rows, trades)
    index = pd.to_datetime([r["ts"] for r in rows], unit="s", utc=True)
    minutes = pd.DataFrame(
        {k: np.fromiter((r[k] for r in rows), dtype=np.float64, count=len(rows))
         for k in ("o", "h", "l", "c")},
        index=index,
    )
    signals = [
        Signal(pd.Timestamp(t["decision"], unit="s", tz="UTC") + pd.Timedelta(nanoseconds=1),
               t["side"], t["risk"], t["risk"] * 1.5, STRATEGY)
        for t in trades
    ]
    settings = Settings(ounces=1.0, roundtrip_cost_per_ounce=source.FEE,
                        max_entry_delay_minutes=1, close_at_end=True)
    canonical = run(minutes, signals, settings)
    fast = run_fast(minutes, signals, settings)
    pd.testing.assert_frame_equal(
        canonical.trades, fast.trades, check_dtype=False, check_exact=False,
        atol=1e-8, rtol=0,
    )
    pd.testing.assert_frame_equal(
        canonical.equity, fast.equity, check_dtype=False, check_exact=False,
        atol=1e-8, rtol=0,
    )
    if (canonical.expired_signals != fast.expired_signals
            or canonical.pending_at_end != fast.pending_at_end
            or canonical.expired_signals or canonical.pending_at_end):
        raise AssertionError("Canonical pending/expired signals or fast mismatch")
    if len(canonical.trades) != len(trades):
        raise AssertionError("Canonical trade count differs from frozen one-slot source")
    for original, (_, actual) in zip(trades, canonical.trades.iterrows()):
        if (pd.Timestamp(original["entry_at"], unit="s", tz="UTC") != actual["entry_at"]
                or pd.Timestamp(original["exit_at"], unit="s", tz="UTC") != actual["closed_at"]
                or original["side"] != actual["side"]):
            raise AssertionError("Source/canonical entry, exit or direction differs")
        for key, field in (
            ("entry_price", "entry_price"), ("exit_price", "exit_price"),
            ("gross", "gross_pnl"), ("fee", "cost"), ("net", "net_pnl"),
        ):
            if not np.isclose(original[key], actual[field], rtol=0, atol=1e-7):
                raise AssertionError(f"Source/canonical {key} differs")
    marks = _source_equity_marks(rows, trades)
    np.testing.assert_allclose(
        marks, canonical.equity["equity"].to_numpy(dtype=float),
        rtol=0, atol=1e-7,
        err_msg="Source/canonical observed M1 close-equity mismatch",
    )
    if len(marks) != len(rows) or not np.isclose(
        expected["max_observed_m1_global_close_dd_usd_per_oz"],
        np.max(np.maximum.accumulate(np.r_[0.0, marks]) - np.r_[0.0, marks]),
        atol=1e-7, rtol=0,
    ):
        raise AssertionError("Source M1 drawdown does not reconcile")
    booked = {}
    for t in canonical.trades.itertuples(index=False):
        month = pd.Timestamp(t.closed_at).strftime("%Y-%m")
        item = booked.setdefault(month, [0.0, 0, 0.0])
        item[0] += float(t.net_pnl)
        item[1] += 1
        item[2] += float(t.cost)
    for month, original in expected["monthly"].items():
        net, count, fees = booked.get(month, (0.0, 0, 0.0))
        if (not np.isclose(original["net_usd_per_oz"], net, atol=1e-7, rtol=0)
                or original["trades"] != count
                or not np.isclose(original["fees_usd_per_oz"], fees, atol=1e-7, rtol=0)):
            raise AssertionError(f"Source/canonical monthly accounting differs: {month}")
    return {
        "status": "BID_PROXY_CANONICAL_PARITY_ONLY_NOT_BROKER_FILLS_NOT_OOS",
        "observed_m1": len(rows),
        "source_selected_trades": len(trades),
        "source_skipped_capacity": skipped["skipped_capacity"],
        "source_skipped_gate": skipped["skipped_gate"],
        "canonical_run_fast_trade_and_m1_parity": True,
        "source_vs_canonical_trade_and_m1_parity": True,
        "net_usd_per_oz": expected["net_usd_per_oz"],
        "fees_usd_per_oz": expected["fees_usd_per_oz"],
        "positive_months": expected["positive_months"],
        "months_observed": expected["months_observed"],
        "worst_month_utc": expected["worst_month_utc"],
        "worst_month_net_usd_per_oz": expected["monthly"][expected["worst_month_utc"]]["net_usd_per_oz"],
        "max_observed_m1_global_close_dd_usd_per_oz":
            expected["max_observed_m1_global_close_dd_usd_per_oz"],
        "original_bidask_broker_execution_verified": False,
        "prospective_oos_verified": False,
        "approved_strategies": 0,
    }


def verify_private_zip(path: Path, years: tuple[int, ...] = (2012, 2013)) -> dict:
    """Verify original SHA by streaming; never publish source rows or receipts."""
    if not years or len(set(years)) != len(years) or any(
        type(y) is not int or not 2010 <= y <= 2026 for y in years
    ):
        raise ValueError("Years must be unique observed historical years")
    digest = sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    if digest.hexdigest() != source.SOURCE_SHA:
        raise ValueError("Original private Gold ZIP SHA256 mismatch")
    result = {}
    with zipfile.ZipFile(path) as archive:
        for year in years:
            rows = json.loads(archive.read(f"{year}.json"))
            result[str(year)] = verify_rows(rows)
    return {
        "source_sha256_verified": True,
        "private_source_not_published": True,
        "historically_exposed_not_clean_oos": True,
        "years": result,
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("private_zip", type=Path)
    parser.add_argument("--years", type=int, nargs="+", default=[2012, 2013])
    parser.add_argument("--out", type=Path, required=True,
                        help="LOCAL aggregate JSON path only (never raw BID/ASK)")
    args = parser.parse_args(argv)
    report = verify_private_zip(args.private_zip, tuple(args.years))
    args.out.write_text(json.dumps(report, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    print(json.dumps({"status": "SOURCE_CANONICAL_PARITY_CHECK_COMPLETE",
                      "years": {year: {"trades": data["source_selected_trades"],
                                       "net_usd_per_oz": data["net_usd_per_oz"]}
                                for year, data in report["years"].items()}}, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
